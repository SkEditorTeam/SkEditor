using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace SkEditor.SourceGenerators;

[Generator]
public class TranslateStringsGenerator : IIncrementalGenerator
{
    private const string EnglishJsonFileName = "English.json";
    
    private static readonly DiagnosticDescriptor MissingJsonRule = new(
        id: "SKED001",
        title: "Missing translation file",
        messageFormat: "Resource '{0}' was not found in AdditionalFiles",
        category: "SourceGenerator",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<AdditionalText?> jsonFile = context
            .AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path) == EnglishJsonFileName)
            .Collect()
            .Select((files, _) => files.FirstOrDefault());

        context.RegisterSourceOutput(jsonFile, (ctx, additionalText) =>
        {
            if (additionalText is null)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(MissingJsonRule, Location.None, EnglishJsonFileName));
                return;
            }

            string json = additionalText.GetText()?.ToString() ?? string.Empty;

            Utf8JsonReader reader = new(Encoding.UTF8.GetBytes(json));
            List<string> keys = [];
            reader.Read();

            if (reader.TokenType != JsonTokenType.StartObject)
            {
                throw new JsonException("Expected start of JSON object");
            }

            while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)
            {
                string key = reader.GetString()!;
                reader.Read();
                _ = reader.GetString()!;

                keys.Add(key);
            }

            string classSource = $$"""
                                   // <auto-generated />
                                   namespace SkEditor.Core.Localization;

                                   public enum TranslationKey
                                   {
                                        None = 0,
                                        {{string.Join("\n,", keys.Select(k => $"{k}"))}}
                                   }
                                   """;

            string formattedCode = CSharpSyntaxTree.ParseText(classSource)
                .GetRoot()
                .NormalizeWhitespace()
                .ToFullString();
            ctx.AddSource("TranslationKey.g.cs", formattedCode);
        });
    }
}